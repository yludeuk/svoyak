"""Патч 2 для parse_docx.py: добавляет правила для theme_comment и author."""
with open("parse_docx.py", "r", encoding="utf-8") as f:
    content = f.read()

old = '''1. theme:
- название темы (без номера и автора в скобках)
- определяется по позиции вопроса в раунде
- если определить невозможно — null

2. price:
- число (10, 20, 30, 40, 50...) если есть
- иначе null

3. question:
- полный текст вопроса
- БЕЗ строки с ценой
- БЕЗ "Ответ:", "Комментарий:", "Источник:"
- сохраняй формулировку как есть

4. answer:
- основной ответ

5. accepted_answers:
- из блока "Зачёт"
- разбей на список
- если нет — null

6. comment:
- текст после "Комментарий:" (имеется в виду комментарий К ВОПРОСУ, не к теме)
- если нет — null

7. sources:
- все источники
- если несколько — массив
- если один — массив из одного элемента
- если нет — null'''

new = '''1. theme:
- название темы (без номера и автора в скобках)
- определяется по позиции вопроса в раунде
- если определить невозможно — null

2. theme_comment:
- текст комментария к теме (идёт после названия темы, обычно начинается с "Комментарий к теме:" или просто описательный текст перед первым вопросом)
- если нет — null

3. author:
- автор темы (из строки "Автор: ..." которая идёт сразу после названия темы)
- если нет — null

4. price:
- число (10, 20, 30, 40, 50...) если есть
- иначе null

5. question:
- полный текст вопроса
- БЕЗ строки с ценой
- БЕЗ "Ответ:", "Комментарий:", "Источник:"
- сохраняй формулировку как есть

6. answer:
- основной ответ

7. accepted_answers:
- из блока "Зачёт"
- разбей на список
- если нет — null

8. comment:
- текст после "Комментарий:" (имеется в виду комментарий К ВОПРОСУ, не к теме)
- если нет — null

9. sources:
- все источники
- если несколько — массив
- если один — массив из одного элемента
- если нет — null'''

if old not in content:
    print("ОШИБКА: блок правил не найден")
    raise SystemExit(1)

content = content.replace(old, new)

with open("parse_docx.py", "w", encoding="utf-8") as f:
    f.write(content)

print("OK: правила добавлены")
